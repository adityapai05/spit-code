-- 3) CONTINUE HANDLER FOR DUPLICATE VALUES

DELIMITER //

CREATE PROCEDURE insert_product_continue_40(
    IN p_supplierId INT,
    IN p_productId INT
)
BEGIN
    DECLARE CONTINUE HANDLER FOR 1062
    SELECT 'DUPLICATE VALUE INSERTION NOT ALLOWED' AS MESSAGE;

    INSERT INTO SupplierProducts_40
    VALUES (p_supplierId, p_productId);

    SELECT COUNT(*) AS Total_Rows
    FROM SupplierProducts_40;
END
//


